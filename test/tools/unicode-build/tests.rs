//! Generator regressions: manifest admission, drift detection, clean-directory
//! replay and the minimal perfect hash shared with the naming runtime.
use super::*;
use std::sync::atomic::{AtomicUsize, Ordering};

fn repository() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// A private scratch directory removed on drop.
struct Scratch(PathBuf);
impl Scratch {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let path = std::env::temp_dir().join(format!(
            "unicode-build-test-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::SeqCst)
        ));
        fs::create_dir(&path).unwrap();
        Self(path)
    }
}
impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

/// A product root holding the manifest and every file it pins.
fn product_copy() -> (Scratch, Manifest) {
    let root = Scratch::new();
    let manifest =
        Manifest::parse(&fs::read_to_string(repository().join(MANIFEST)).unwrap()).unwrap();
    for path in std::iter::once(Path::new(MANIFEST))
        .chain(manifest.entries.iter().map(|e| e.path.as_path()))
    {
        let target = root.0.join(path);
        fs::create_dir_all(target.parent().unwrap()).unwrap();
        fs::copy(repository().join(path), target).unwrap();
    }
    (root, manifest)
}

#[test]
fn the_repository_tables_are_reproduced_from_their_pinned_inputs() {
    assert!(run(&repository(), Mode::Check).unwrap().ends_with("PASS"));
}

#[test]
fn input_and_output_drift_are_rejected() {
    let (root, manifest) = product_copy();
    assert!(run(&root.0, Mode::Check).is_ok());
    let input = root
        .0
        .join(&manifest.entry("derived-normalization-props").path);
    let original = fs::read(&input).unwrap();
    let mut changed = original.clone();
    changed.push(b'\n');
    fs::write(&input, &changed).unwrap();
    let error = run(&root.0, Mode::Check).unwrap_err().to_string();
    assert!(error.contains("pinned digest differs"), "{error}");
    fs::write(&input, &original).unwrap();

    let fixture = root.0.join(&manifest.entry("normalization-test").path);
    fs::write(&fixture, b"# truncated\n").unwrap();
    assert!(
        run(&root.0, Mode::Check).is_err(),
        "fixtures are pinned too"
    );
    fs::copy(
        repository().join(&manifest.entry("normalization-test").path),
        &fixture,
    )
    .unwrap();

    let output = root.0.join(&manifest.entry("normalization").path);
    let mut bytes = fs::read(&output).unwrap();
    bytes.extend_from_slice(b"// edited\n");
    fs::write(&output, bytes).unwrap();
    let error = run(&root.0, Mode::Check).unwrap_err().to_string();
    assert!(
        error.contains("differs from the generated bytes"),
        "{error}"
    );
    assert!(!error.contains("manifest digest"), "{error}");
}

#[test]
fn write_restores_outputs_without_touching_input_records() {
    let (root, manifest) = product_copy();
    let output = root.0.join(&manifest.entry("properties").path);
    fs::write(&output, b"// stale\n").unwrap();
    run(&root.0, Mode::Write).unwrap();
    assert_eq!(
        fs::read(&output).unwrap(),
        fs::read(repository().join(&manifest.entry("properties").path)).unwrap()
    );
    assert_eq!(
        fs::read_to_string(root.0.join(MANIFEST)).unwrap(),
        manifest.text
    );
    assert!(run(&root.0, Mode::Check).is_ok());
}

#[test]
fn replay_uses_only_declared_inputs_in_an_empty_directory() {
    let directory = Scratch::new();
    let message = run(&repository(), Mode::Replay(directory.0.clone())).unwrap();
    assert!(message.ends_with("PASS"), "{message}");
    let mut files = Vec::new();
    let mut pending = vec![directory.0.clone()];
    while let Some(path) = pending.pop() {
        for entry in fs::read_dir(path).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                pending.push(path);
            } else {
                files.push(path.strip_prefix(&directory.0).unwrap().to_owned());
            }
        }
    }
    files.sort();
    let manifest =
        Manifest::parse(&fs::read_to_string(repository().join(MANIFEST)).unwrap()).unwrap();
    let mut expected = std::iter::once(PathBuf::from(MANIFEST))
        .chain(manifest.of(Kind::Input).map(|entry| entry.path.clone()))
        .chain(manifest.of(Kind::Output).map(|entry| entry.path.clone()))
        .collect::<Vec<_>>();
    expected.sort();
    assert_eq!(
        files, expected,
        "fixtures and other tree files are not copied"
    );

    let occupied = Scratch::new();
    fs::write(occupied.0.join("stray"), b"").unwrap();
    let error = run(&repository(), Mode::Replay(occupied.0.clone())).unwrap_err();
    assert!(error.to_string().contains("not empty"));
}

#[test]
fn manifest_admits_each_known_record_once_with_safe_paths_and_digests() {
    let text = fs::read_to_string(repository().join(MANIFEST)).unwrap();
    assert!(Manifest::parse(&text).is_ok());
    let digest = "0".repeat(64);
    for (bad, reason) in [
        (text.replace("version\t16.0.0\n", ""), "missing version"),
        (format!("{text}version\t16.0.0\n"), "second version"),
        (
            text.replace("version\t16.0.0", "version\t16.0"),
            "malformed version",
        ),
        (
            format!("{text}output\tproperties\tsrc/x.rs\t{digest}\n"),
            "duplicate role",
        ),
        (
            format!("{text}output\tother\tsrc/x.rs\t{digest}\n"),
            "unknown role",
        ),
        (
            text.replace("src/naming/src/unicode16.rs", "../unicode16.rs"),
            "parent path",
        ),
        (
            text.replace("src/naming/src/unicode16.rs", "/tmp/unicode16.rs"),
            "absolute path",
        ),
    ] {
        assert!(Manifest::parse(&bad).is_err(), "{reason}");
    }
    let upper = text
        .lines()
        .map(|line| match line.split('\t').collect::<Vec<_>>()[..] {
            ["output", role, path, digest] => {
                format!("output\t{role}\t{path}\t{}", digest.to_uppercase())
            }
            _ => line.to_owned(),
        })
        .collect::<Vec<_>>()
        .join("\n");
    assert!(
        Manifest::parse(&upper).is_err(),
        "uppercase digests are not canonical"
    );
    let missing_output = text
        .lines()
        .filter(|line| !line.starts_with("output\tproperties"))
        .collect::<Vec<_>>()
        .join("\n");
    assert!(Manifest::parse(&missing_output).is_err());
}

/// The naming runtime's lookup (src/naming/src/unicode/perfect_hash.rs) uses
/// wrapping u32 arithmetic; the generator's wide arithmetic must agree.
fn runtime_hash(key: u32, salt: u32, n: usize) -> usize {
    let y = key.wrapping_add(salt).wrapping_mul(2_654_435_769);
    let y = y ^ key.wrapping_mul(0x3141_5926);
    ((u64::from(y) * n as u64) >> 32) as usize
}

#[test]
fn generator_hash_matches_runtime_lookup_for_every_slot() {
    let mut keys = (0..5000u32)
        .map(|value| value.wrapping_mul(0x9e37_79b9) ^ (value << 7))
        .collect::<Vec<_>>();
    keys.extend([0, u32::MAX, 0xffff_0000, 0x0001_0000]);
    keys.sort_unstable();
    keys.dedup();
    let (salts, slots) = normalization::minimal_perfect_hash(&keys).unwrap();
    assert_eq!(salts.len(), keys.len());
    for &key in &keys {
        for salt in [0, 1, 255, 32767] {
            assert_eq!(
                normalization::hash(key, salt, keys.len()),
                runtime_hash(key, salt, keys.len())
            );
        }
        let salt = u32::from(salts[runtime_hash(key, 0, salts.len())]);
        assert_eq!(slots[runtime_hash(key, salt, salts.len())], key);
    }
}

#[test]
fn normalization_data_rejects_malformed_records() {
    let unicode = "00C0;LATIN CAPITAL LETTER A WITH GRAVE;Lu;0;L;0041 0300;;;;N;;;;00E0;\n";
    let props = "0340..0341    ; Full_Composition_Exclusion\n0300..0304    ; NFC_QC; M\n";
    assert!(normalization::parse(unicode, props).is_ok());
    assert!(normalization::parse("00C0;short;Lu\n", props).is_err());
    assert!(
        normalization::parse(
            unicode,
            "0300    ; NFC_QC; Q\n0340 ; Full_Composition_Exclusion\n"
        )
        .is_err()
    );
    assert!(normalization::parse(unicode, "0340 ; Full_Composition_Exclusion\n").is_err());
}
