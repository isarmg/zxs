//! Business-only field capture. No authoritative State or disk format changes.
use super::{Arc, BusinessMetadataProjection, State};

impl BusinessMetadataProjection {
    pub(super) fn capture(state: &State) -> Self {
        // Exhaustive classification makes new authority-bearing fields a compile
        // error here instead of accidentally retaining them in every read.
        let State {
            sequence,
            business_generation,
            repositories,
            histories,
            branches,
            file_selections,
            directory_branches,
            directory_trees,
            file_write_origins,
            file_contexts,
            file_path_nodes,
            file_metadata_nodes,
            file_branch_merges,
            file_branch_aliases,
            file_node_parents,
            file_path_notes,
            directory_tree_selections,
            file_locations,
            file_backup_paths,
            file_backup_policies,
            directory_selections,
            directory_selection_generations,
            file_selection_generations,
            file_notes,
            version_notes,
            file_names,
            commits,
            versions,
            placements,
            merge_links,
            history_boundaries,
            content_states,
            operations: _,
            plans: _,
            placement_rules,
            protection_policies,
            operation_principals: _,
            control_auth: _,
            events: _,
            topology_generation,
        } = state;
        Self(Arc::new(State {
            sequence: *sequence,
            business_generation: *business_generation,
            repositories: repositories.clone(),
            histories: histories.clone(),
            branches: branches.clone(),
            file_selections: file_selections.clone(),
            directory_branches: directory_branches.clone(),
            directory_trees: directory_trees.clone(),
            file_write_origins: file_write_origins.clone(),
            file_contexts: file_contexts.clone(),
            file_path_nodes: file_path_nodes.clone(),
            file_metadata_nodes: file_metadata_nodes.clone(),
            file_branch_merges: file_branch_merges.clone(),
            file_branch_aliases: file_branch_aliases.clone(),
            file_node_parents: file_node_parents.clone(),
            file_path_notes: file_path_notes.clone(),
            directory_tree_selections: directory_tree_selections.clone(),
            file_locations: file_locations.clone(),
            file_backup_paths: file_backup_paths.clone(),
            file_backup_policies: file_backup_policies.clone(),
            directory_selections: directory_selections.clone(),
            directory_selection_generations: directory_selection_generations.clone(),
            file_selection_generations: file_selection_generations.clone(),
            file_notes: file_notes.clone(),
            version_notes: version_notes.clone(),
            file_names: file_names.clone(),
            commits: commits.clone(),
            versions: versions.clone(),
            placements: placements.clone(),
            merge_links: merge_links.clone(),
            history_boundaries: history_boundaries.clone(),
            content_states: content_states.clone(),
            operations: Default::default(),
            plans: Default::default(),
            placement_rules: placement_rules.clone(),
            protection_policies: protection_policies.clone(),
            operation_principals: Default::default(),
            control_auth: None,
            events: Default::default(),
            topology_generation: *topology_generation,
        }))
    }
}
