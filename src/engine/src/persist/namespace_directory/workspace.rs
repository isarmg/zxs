//! Original workspace input for directories introduced by that decision.
//! This is not a workspace completion receipt and cannot replace either saved
//! commit-request mirror. It carries no staging path, lease or physical handle.
use crate::business::WorkspaceInput;
use crate::engine::FreshLayoutError as Failure;
use crate::{CommitRequest, ContentHash, NamespaceOperation, OperationResult, Result, State};
use data_serialization::{Deserialize, Serialize};
use name_policy::PortablePath;
use storage_contract::{CommitId, EntryId, Generation, Id, IdKind};

const FIELD: &str = "workspace_directory_source";
const WIRE_FIELD: &str = "workspace_directory_wire_source";

pub(crate) enum WorkspaceIdentity {}
impl IdKind for WorkspaceIdentity {
    const PREFIX: &'static str = "ws";
}

#[derive(Clone, Serialize, Deserialize)]
#[serialization(deny_unknown_fields)]
pub(crate) struct File {
    pub(crate) item_id: EntryId,
    pub(crate) path: PortablePath,
    pub(crate) hash: ContentHash,
    #[serialization(with = "storage_contract::u64_string")]
    pub(crate) size: u64,
    generation: Generation,
}

#[derive(Clone, Serialize, Deserialize)]
#[serialization(deny_unknown_fields)]
struct Manifest {
    workspace_id: Id<WorkspaceIdentity>,
    base_head: CommitId,
    files: Vec<File>,
    namespace_operations: Vec<NamespaceOperation>,
}

#[derive(Serialize, Deserialize)]
#[serialization(deny_unknown_fields)]
pub(crate) struct Source {
    request: CommitRequest,
    manifest: Manifest,
    directories: Vec<EntryId>,
}

/// Original authenticated public request, kept inside the permanent decision
/// only. Native evidence keeps its existing encoding and digest.
#[derive(Serialize, Deserialize)]
#[serialization(deny_unknown_fields)]
struct WireSource {
    source: Source,
    body: json_codec::Value,
}

impl Source {
    pub(crate) fn request(&self) -> &CommitRequest { &self.request }
    pub(crate) fn files(&self) -> &[File] { &self.manifest.files }
    pub(crate) fn operations(&self) -> &[NamespaceOperation] {
        &self.manifest.namespace_operations
    }
    pub(crate) fn directories(&self) -> &[EntryId] { &self.directories }
}

/// These IDs are generated by the existing namespace constructors, in their
/// original order. A trace is retained only for admitted file-manager main writes.
pub(crate) struct Allocations {
    enabled: bool,
    directories: Vec<EntryId>,
}
impl Allocations {
    pub(crate) fn new(enabled: bool) -> Self {
        Self { enabled, directories: Vec::new() }
    }

    pub(crate) fn next(&mut self, prefix: &str) -> Result<String> {
        let id = storage_contract::new_id(prefix)?;
        if self.enabled {
            if prefix != "entry" {
                return Err(Failure::NamespaceSource.into());
            }
            self.directories.push(id.parse()?);
        }
        Ok(id)
    }

    pub(crate) fn attach(
        self,
        result: &mut json_codec::Value,
        workspace: &(impl WorkspaceInput + ?Sized),
        request: &CommitRequest,
        wire: Option<&crate::wire::WireCommit>,
    ) -> Result<()> {
        if self.directories.is_empty() {
            return Ok(());
        }
        let mut request = request.clone();
        request.request_digest = None;
        let manifest = Manifest {
            workspace_id: workspace.workspace_id().parse()?,
            base_head: workspace.base_head().parse()?,
            files: workspace.files().map(|file| Ok(File {
                item_id: file.item().parse()?, path: file.path().clone(),
                hash: file.hash().clone(), size: file.size(),
                generation: Generation::new(file.generation()),
            })).collect::<Result<Vec<_>>>()?,
            namespace_operations: workspace.namespace_operations().to_vec(),
        };
        let source = Source { request, manifest, directories: self.directories };
        let (field, value) = match wire {
            Some(wire) => (WIRE_FIELD, json_codec::to_value(WireSource {
                source, body: wire.body.clone(),
            })),
            None => (FIELD, json_codec::to_value(source)),
        };
        result[field] = value.map_err(Failure::NamespaceRecord)?;
        Ok(())
    }
}

pub(crate) fn decode(state: &State, result: &OperationResult, maximum: usize) -> Result<Source> {
    if result.kind != "workspace.commit" || result.sequence > state.sequence {
        return Err(Failure::NamespaceSource.into());
    }
    let (value, encoded_source, wire) = match (
        result.result.get(FIELD), result.result.get(WIRE_FIELD),
    ) {
        (Some(value), None) => (value, value, false),
        (None, Some(value)) => {
            let source = value.get("source").ok_or(Failure::NamespaceSource)?;
            let placements = value.get("body")
                .and_then(|body| body.get("file_placement"))
                .and_then(json_codec::Value::as_object).ok_or(Failure::NamespaceSource)?;
            if placements.len() > maximum {
                return Err(Failure::NamespaceSource.into());
            }
            (value, source, true)
        }
        _ => return Err(Failure::NamespaceSource.into()),
    };
    // Bound all newly decoded vectors by the actual admitted commit's entries.
    for array in [
        encoded_source.get("directories"),
        encoded_source.get("manifest").and_then(|value| value.get("files")),
        encoded_source.get("manifest").and_then(|value| value.get("namespace_operations")),
    ] {
        if array.and_then(json_codec::Value::as_array)
            .is_none_or(|rows| rows.len() > maximum)
        {
            return Err(Failure::NamespaceSource.into());
        }
    }
    let (source, body) = if wire {
        let retained: WireSource = json_codec::from_value(value.clone())
            .map_err(Failure::NamespaceRecord)?;
        if json_codec::to_value(&retained).map_err(Failure::NamespaceRecord)? != *value {
            return Err(Failure::NamespaceSource.into());
        }
        (retained.source, Some(retained.body))
    } else {
        let source: Source = json_codec::from_value(value.clone())
            .map_err(Failure::NamespaceRecord)?;
        if json_codec::to_value(&source).map_err(Failure::NamespaceRecord)? != *value {
            return Err(Failure::NamespaceSource.into());
        }
        (source, None)
    };
    let principal = state.operation_principals.get(&result.operation_id)
        .ok_or(Failure::NamespaceSource)?;
    if source.request.operation_id != result.operation_id
        || source.request.principal != *principal
        || source.request.request_digest.is_some()
        || source.request.workspace_id != source.manifest.workspace_id.to_string()
        || source.request.expected_head != source.manifest.base_head.to_string()
        || source.directories.is_empty()
    {
        return Err(Failure::NamespaceSource.into());
    }
    if let Some(body) = body {
        require_original_wire(state, result, &source, body)?;
    } else {
        let manifest_hash = storage_contract::object_hash("workspace", &source.manifest)?;
        let input = json_codec::json!({
            "request":source.request, "sealed_manifest_hash":manifest_hash,
        });
        if crate::Engine::native_request_digest("workspace.commit", principal, &input)?
            != result.request_digest
        {
            return Err(Failure::NamespaceSource.into());
        }
    }
    Ok(source)
}

fn require_original_wire(
    state: &State, result: &OperationResult, source: &Source, body: json_codec::Value,
) -> Result<()> {
    let request = &source.request;
    let envelope = crate::PublicCommitEnvelope::parse(&request.workspace_id, body)
        .map_err(|_| Failure::NamespaceSource)?;
    let branch = result.branch_id.as_deref().ok_or(Failure::NamespaceSource)?;
    let history = result.history_tree_id.as_deref().ok_or(Failure::NamespaceSource)?;
    let history = state.histories.get(history).ok_or(Failure::NamespaceSource)?;
    let repository = state.repositories.get(&history.repository_id)
        .filter(|repo| repo.file_manager_root && repo.main_branch_id == branch)
        .ok_or(Failure::NamespaceSource)?;
    if envelope.digest() != result.request_digest
        || envelope.claimed_digest() != result.request_digest
        || envelope.operation_id() != request.operation_id
        || envelope.workspace_id() != request.workspace_id
        || envelope.repository_id() != repository.repository_id
        || envelope.branch_id() != branch
        || envelope.expected_head() != request.expected_head
        || envelope.fencing_token() != request.fencing_token
        || envelope.message() != request.message
        || envelope.requested_protection() != "strict"
        || storage_contract::parse_u64_decimal(envelope.expected_topology_generation()).is_err()
        || source.manifest.files.is_empty()
        || envelope.file_placement().len() != source.manifest.files.len()
        || source.manifest.files.iter().any(|file| {
            !envelope.file_placement().contains_key(&file.item_id.to_string())
        })
    {
        return Err(Failure::NamespaceSource.into());
    }
    let hash = crate::wire::sealed_manifest_hash(
        &request.workspace_id, branch, &request.expected_head, request.fencing_token,
        source.manifest.files.iter().map(|file| crate::wire::sealed_manifest_item(
            file.item_id, &file.path, file.size, &file.hash, file.generation.get(),
        )).collect(),
        &source.manifest.namespace_operations,
    )?;
    if hash != envelope.sealed_manifest_hash() {
        return Err(Failure::NamespaceSource.into());
    }
    Ok(())
}
