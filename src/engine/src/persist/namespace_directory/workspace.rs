//! Original native workspace input for directories introduced by that decision.
//! This is not a workspace completion receipt and cannot replace either saved
//! commit-request mirror. It carries no staging path, lease or physical handle.
use crate::business::WorkspaceInput;
use crate::engine::FreshLayoutError as Failure;
use crate::{CommitRequest, ContentHash, NamespaceOperation, OperationResult, Result, State};
use data_serialization::{Deserialize, Serialize};
use name_policy::PortablePath;
use storage_contract::{CommitId, EntryId, Generation, Id, IdKind};

const FIELD: &str = "workspace_directory_source";

pub(crate) enum WorkspaceIdentity {}
impl IdKind for WorkspaceIdentity {
    const PREFIX: &'static str = "ws";
}

#[derive(Clone, Serialize, Deserialize)]
#[serialization(deny_unknown_fields)]
pub(crate) struct File {
    pub(crate) item_id: EntryId,
    pub(crate) path: PortablePath,
    pub(crate) hash: ContentHash,
    #[serialization(with = "storage_contract::u64_string")]
    pub(crate) size: u64,
    generation: Generation,
}

#[derive(Clone, Serialize, Deserialize)]
#[serialization(deny_unknown_fields)]
struct Manifest {
    workspace_id: Id<WorkspaceIdentity>,
    base_head: CommitId,
    files: Vec<File>,
    namespace_operations: Vec<NamespaceOperation>,
}

#[derive(Serialize, Deserialize)]
#[serialization(deny_unknown_fields)]
pub(crate) struct Source {
    request: CommitRequest,
    manifest: Manifest,
    directories: Vec<EntryId>,
}

impl Source {
    pub(crate) fn request(&self) -> &CommitRequest { &self.request }
    pub(crate) fn files(&self) -> &[File] { &self.manifest.files }
    pub(crate) fn operations(&self) -> &[NamespaceOperation] {
        &self.manifest.namespace_operations
    }
    pub(crate) fn directories(&self) -> &[EntryId] { &self.directories }
}

/// These IDs are generated by the existing namespace constructors, in their
/// original order. A trace is retained only for native file-manager main writes.
pub(crate) struct Allocations {
    enabled: bool,
    directories: Vec<EntryId>,
}
impl Allocations {
    pub(crate) fn new(enabled: bool) -> Self {
        Self { enabled, directories: Vec::new() }
    }

    pub(crate) fn next(&mut self, prefix: &str) -> Result<String> {
        let id = storage_contract::new_id(prefix)?;
        if self.enabled {
            if prefix != "entry" {
                return Err(Failure::NamespaceSource.into());
            }
            self.directories.push(id.parse()?);
        }
        Ok(id)
    }

    pub(crate) fn attach(
        self,
        result: &mut json_codec::Value,
        workspace: &(impl WorkspaceInput + ?Sized),
        request: &CommitRequest,
    ) -> Result<()> {
        if self.directories.is_empty() {
            return Ok(());
        }
        let mut request = request.clone();
        request.request_digest = None;
        let manifest = Manifest {
            workspace_id: workspace.workspace_id().parse()?,
            base_head: workspace.base_head().parse()?,
            files: workspace.files().map(|file| Ok(File {
                item_id: file.item().parse()?, path: file.path().clone(),
                hash: file.hash().clone(), size: file.size(),
                generation: Generation::new(file.generation()),
            })).collect::<Result<Vec<_>>>()?,
            namespace_operations: workspace.namespace_operations().to_vec(),
        };
        result[FIELD] = json_codec::to_value(Source {
            request, manifest, directories: self.directories,
        }).map_err(Failure::NamespaceRecord)?;
        Ok(())
    }
}

pub(crate) fn decode(state: &State, result: &OperationResult, maximum: usize) -> Result<Source> {
    if result.kind != "workspace.commit" || result.sequence > state.sequence {
        return Err(Failure::NamespaceSource.into());
    }
    let value = result.result.get(FIELD).ok_or(Failure::NamespaceSource)?;
    // Bound all newly decoded vectors by the actual admitted commit's entries.
    for array in [
        value.get("directories"),
        value.get("manifest").and_then(|value| value.get("files")),
        value.get("manifest").and_then(|value| value.get("namespace_operations")),
    ] {
        if array.and_then(json_codec::Value::as_array)
            .is_none_or(|rows| rows.len() > maximum)
        {
            return Err(Failure::NamespaceSource.into());
        }
    }
    let source: Source = json_codec::from_value(value.clone()).map_err(Failure::NamespaceRecord)?;
    let principal = state.operation_principals.get(&result.operation_id)
        .ok_or(Failure::NamespaceSource)?;
    let manifest_hash = storage_contract::object_hash("workspace", &source.manifest)?;
    let input = json_codec::json!({
        "request":source.request, "sealed_manifest_hash":manifest_hash,
    });
    if json_codec::to_value(&source).map_err(Failure::NamespaceRecord)? != *value
        || source.request.operation_id != result.operation_id
        || source.request.principal != *principal
        || source.request.request_digest.is_some()
        || source.request.workspace_id != source.manifest.workspace_id.to_string()
        || source.request.expected_head != source.manifest.base_head.to_string()
        || source.directories.is_empty()
        || crate::Engine::native_request_digest("workspace.commit", principal, &input)?
            != result.request_digest
    {
        return Err(Failure::NamespaceSource.into());
    }
    Ok(source)
}
