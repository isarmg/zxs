"""Emit the static unit corner used by management; see web/NOTICE.md."""
from math import cos, pi, sin

CIRCLE_RATIO = 0.4
MAX_CURVATURE = 1.486024529088757
JOIN = 0.375
SIMPSON_CELLS = 512
CHORDS = 64
TURN = pi * (1 - CIRCLE_RATIO) / 2
RADIUS = 1 / MAX_CURVATURE
TRANSITION_LENGTH = TURN * RADIUS
CORNER_LENGTH = (2 * TURN + pi * CIRCLE_RATIO / 2) * RADIUS


def heading(u):
    # Integral of q(u) = 6u^5 - 15u^4 + 10u^3.
    return TURN * u**4 * (u * (u - 3) + 2.5)


def simpson(start, end):
    angles = [heading(u) for u in (start, (start + end) / 2, end)]
    scale = (end - start) / 6
    return tuple(scale * (f(angles[0]) + 4 * f(angles[1]) + f(angles[2]))
                 for f in (cos, sin))


def transition(t):
    end = t / JOIN
    cells = int(end * SIMPSON_CELLS)
    x, y = simpson(cells / SIMPSON_CELLS, end)
    for i in range(cells):
        dx, dy = simpson(i / SIMPSON_CELLS, (i + 1) / SIMPSON_CELLS)
        x += dx
        y += dy
    return x * TRANSITION_LENGTH, y * TRANSITION_LENGTH


def corner(t):
    if t <= JOIN:
        return transition(t)
    if t >= 1 - JOIN:
        x, y = transition(1 - t)
        return 1 - y, 1 - x
    x, y = transition(JOIN)
    first = TURN / 2
    angle = first + CORNER_LENGTH * MAX_CURVATURE * (t - JOIN)
    return x + RADIUS * (sin(angle) - sin(first)), y + RADIUS * (cos(first) - cos(angle))


def canonical(number):
    rounded = f"{number:.6f}".rstrip("0").rstrip(".")
    return "0" if rounded == "-0" else rounded


def emit():
    print('<!-- Generated by make-g4-corner.py from the archived ZXS G4 profile; see NOTICE.md. -->')
    print('<svg xmlns="http://www.w3.org/2000/svg" class="zxs-g4-defs" width="0" height="0" aria-hidden="true" focusable="false">')
    print('  <defs>')
    print('    <path id="zxs-g4-corner" d="')
    vertices = []
    for i in range(CHORDS + 1):
        x, y = corner(i / CHORDS)
        vertices.append(f"{'M' if i == 0 else 'L'}{canonical(x)} {canonical(y)}")
    for i in range(0, len(vertices), 4):
        print('      ' + ' '.join(vertices[i:i + 4]))
    # The lower-left triangle of this top-right tile lies inside the card.
    print('      L0 1 Z"/>')
    print('  </defs>')
    print('</svg>')


if __name__ == "__main__":
    emit()
