use super::fresh_verifier;

#[test]
fn current_offline_derivation_matches_the_independent_argon2id_vector() {
    // Public synthetic vector carried forward from the old Web fixture:
    // Argon2id v19, memory 65536 KiB, time 3, lanes 4, 32-byte output.
    let salt = [
        0x30, 0x82, 0x11, 0xaa, 0x0b, 0xe0, 0x41, 0xb8, 0x23, 0xdb, 0x6d, 0x23, 0x7e, 0x9d, 0x0c,
        0x3c,
    ];
    let expected: [u8; 32] = [
        0x61, 0xfc, 0x09, 0x49, 0x58, 0xed, 0x8d, 0x25, 0x34, 0xcf, 0x35, 0x7f, 0x3f, 0x74, 0xbd,
        0x9e, 0x74, 0x3f, 0x51, 0x2a, 0xde, 0xdb, 0x0b, 0xc9, 0x32, 0x37, 0xc2, 0x22, 0x3a, 0xd3,
        0x41, 0xb8,
    ];
    let actual = fresh_verifier("correct horse battery staple", &salt).unwrap();
    assert!(
        *actual == expected,
        "offline verifier disagrees with the fixed vector"
    );
}
