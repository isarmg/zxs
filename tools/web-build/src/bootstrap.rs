//! Generate the resource loader and its failure boundary. Product behavior stays in WASM.
const MODULE: &str = "./pkg/zxs.js";
const TIMEOUT_MS: u32 = 30_000;

pub fn loader() -> String {
    TEMPLATE
        .replace(
            "__ZXS_MODULE__",
            &json_codec::to_string(MODULE).expect("literal module path"),
        )
        .replace("__ZXS_TIMEOUT__", &TIMEOUT_MS.to_string())
}

pub fn index() -> &'static str {
    r#"<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="color-scheme" content="light dark"><title>ZXS · 文件与历史</title><link rel="stylesheet" href="./styles/startup.css"><link rel="stylesheet" href="./zxs.css"><link rel="modulepreload" href="./pkg/zxs.js"></head><body><div id="root"><p role="status">正在启动 ZXS。若此提示持续显示，请检查浏览器是否支持 WebAssembly 及服务端资源是否完整。</p></div><script type="module" src="./boot.js"></script></body></html>"#
}

// Generated glue owns resource loading and fallback rendering only. The Rust
// runtime owns font decoding, the application mount and its readiness event.
const TEMPLATE: &str = r#"// Generated by web-build. Resource bootstrap only.
const html = document.documentElement;
if (html.hasAttribute("data-zxs-startup")) throw new Error("Application startup already began");
html.setAttribute("data-zxs-startup", "pending");
html.setAttribute("data-zxs-fonts", "pending");
let settled = false;
let timer;
const stylesheetListeners = [];
function settle(next) {
  if (settled) return false;
  settled = true;
  clearTimeout(timer);
  for (const detach of stylesheetListeners.splice(0)) detach();
  document.removeEventListener("zxs-startup-ready", ready);
  document.removeEventListener("zxs-startup-failed", failed);
  window.removeEventListener("error", scriptError);
  window.removeEventListener("unhandledrejection", scriptError);
  window.removeEventListener("pagehide", pagehide);
  html.setAttribute("data-zxs-startup", next);
  return true;
}
function ready() {
  if (html.getAttribute("data-zxs-startup") === "failed"
      || html.getAttribute("data-zxs-runtime") !== "web-interface") {
    fail("runtime");
    return;
  }
  settle("ready");
}
function failed() { fail("resources"); }
function scriptError(event) { fail("runtime", event.error ?? event.reason); }
function pagehide(event) {
  if (!event.persisted) settle("failed");
}
function fail(stage, error) {
  if (!settle("failed")) return;
  html.removeAttribute("data-zxs-runtime");
  html.removeAttribute("data-zxs-ready");
  // Cancel the Rust lifetime, including any optional pending font work.
  document.dispatchEvent(new Event("zxs-startup-failed"));
  const language = new URL(window.location.href).searchParams.get("lang") ?? html.lang;
  const chinese = language.toLowerCase().startsWith("zh");
  const panel = document.createElement("section");
  panel.id = "zxs-startup-error";
  panel.setAttribute("role", "alert");
  panel.setAttribute("aria-labelledby", "zxs-startup-error-title");
  panel.dataset.stage = stage;
  panel.tabIndex = -1;
  const title = document.createElement("h1");
  title.id = "zxs-startup-error-title";
  title.textContent = chinese ? "页面启动失败" : "Page could not start";
  const message = document.createElement("p");
  message.textContent = chinese
    ? "浏览器缺少必需能力，或页面资源加载失败或超时。请使用现代浏览器并检查网络连接，然后重新加载页面。"
    : "Required browser capabilities are unavailable, or page resources failed to load or timed out. Use a modern browser and check your connection, then reload the page.";
  const retry = document.createElement("button");
  retry.type = "button";
  retry.textContent = chinese ? "重新加载页面" : "Reload page";
  retry.addEventListener("click", () => {
    retry.disabled = true;
    window.location.reload();
  }, { once: true });
  panel.append(title, message, retry);
  document.body.append(panel);
  panel.focus({ preventScroll: true });
  console.error("Application startup failed", stage, error ?? "");
}
document.addEventListener("zxs-startup-ready", ready);
document.addEventListener("zxs-startup-failed", failed);
window.addEventListener("error", scriptError);
window.addEventListener("unhandledrejection", scriptError);
window.addEventListener("pagehide", pagehide);
timer = setTimeout(() => fail("timeout"), __ZXS_TIMEOUT__);
// CSS remains required, unlike optional font downloads. A missing stylesheet
// cannot become a falsely ready, unstyled app when font readiness is decoupled.
function stylesheet(link) {
  if (link.sheet) return Promise.resolve();
  return new Promise((resolve, reject) => {
    const loaded = () => { detach(); resolve(); };
    const failed = () => { detach(); reject(new Error("Required stylesheet failed")); };
    const detach = () => {
      link.removeEventListener("load", loaded);
      link.removeEventListener("error", failed);
    };
    stylesheetListeners.push(detach);
    link.addEventListener("load", loaded, { once: true });
    link.addEventListener("error", failed, { once: true });
  });
}
// Import after the failure boundary exists so a missing binding module is visible.
Promise.all([
  Promise.resolve().then(() => import(__ZXS_MODULE__)),
  ...Array.from(document.querySelectorAll('link[rel="stylesheet"]'), stylesheet),
])
  .then(([module]) => { if (!settled) return module.default(); })
  .catch(error => fail("runtime", error));
"#;

