//! NFC tables for the naming policy: canonical combining classes, canonical
//! full decompositions, canonical compositions and the NFC quick check.
//!
//! The table layout, minimal perfect hash and text format are ported from
//! `scripts/unicode.py` of unicode-normalization 0.1.24 (MIT OR Apache-2.0,
//! The Rust Project Developers), so retained tables keep their exact bytes.
//! Only the tables reachable from the naming policy are generated.
use crate::{Result, cp};
use std::{collections::BTreeMap, fmt::Write as _};

const S_BASE: u32 = 0xAC00;
const S_COUNT: u32 = 19 * 21 * 28;

